def main():
    out: dict[str, list[str]] = {}
    def add(k: str, vs):
        k = k.strip()
        if not k:
            return
        lst = out.setdefault(k, [])
        for v in vs:
            v = v.strip()
            if v and v != k and v not in lst:
                lst.append(v)
    for g in EQUIV:
        terms = list(dict.fromkeys(t for t in g if t.strip() and "ترimmer" not in t))
        for t in terms:
            add(t, [x for x in terms if x != t])
    for k, vs in ONE_WAY.items():
        if vs:
            add(k, vs)
    out = {k: v for k, v in out.items() if v}
    print(f"synonym keys: {len(out)}; expansions: {sum(len(v) for v in out.values())}")
    if "--dry" not in sys.argv:
        p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "data", "synonyms.json")
        with open(p, "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print("wrote", os.path.normpath(p))

