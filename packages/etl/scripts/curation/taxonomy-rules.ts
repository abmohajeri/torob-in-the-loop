function compileKeyword(raw: string): RegExp {
  const prefix = raw.endsWith('*');
  const kw = normalizeForSearch(prefix ? raw.slice(0, -1) : raw);
  const esc = kw.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(?:^| )${esc}${prefix ? '' : '(?= |$)'}`);
}

interface CompiledRule {
  rule: Rule;
  patterns: { kw: string; re: RegExp }[];
}

let compiled: CompiledRule[] | null = null;
function compiledRules(): CompiledRule[] {
  if (!compiled) {
    compiled = RULES.map((rule) => ({
      rule,
      patterns: rule.any.map((kw) => ({ kw, re: compileKeyword(kw) })),
    }));
  }
  return compiled;
}

export interface Classification {
  group: GroupId;
  /** 'override' | '<rule id>:<keyword>' | 'fallback' */
  via: string;
}

/** Classify one leaf category name into a group (deterministic). */
export function classifyCategory(name: string): Classification {
  const o = OVERRIDES[name];
  if (o) return { group: o, via: 'override' };
  const norm = normalizeForSearch(name);
  for (const { rule, patterns } of compiledRules()) {
    for (const p of patterns) {
      if (p.re.test(norm)) return { group: rule.group, via: `${rule.id}:${p.kw}` };
    }
  }
  return { group: 'other', via: 'fallback' };
}
