/**
 * Leaf category → category group classifier used to (re)generate data/taxonomy.json "groups".
 *
 * How it works
 *  1. OVERRIDES (exact leaf names, reviewed by hand) win.
 *  2. Otherwise the first RULE whose keyword matches the normalized leaf name decides.
 *     Keywords are normalized with the shared `normalizeForSearch`, then matched as whole words
 *     (space-bounded word sequences). A trailing `*` turns the last word into a prefix match.
 *  3. Nothing matched → 'other' (reported by build-taxonomy so it can be reviewed).
 *
 * Rule order encodes precedence, e.g. «… خودرو» always lands in auto before generic words such as
 * «چراغ» (lighting) or «باتری» (electrical) are considered; «… گوشی/تبلت» lands in mobile before
 * «شارژر/کابل» rules, and pets go before food/beauty («شامپو و لوسیون حیوانات»).
 *
 * Group semantics (see shared CATEGORY_GROUPS):
 *  - food also hosts pet food & pet supplies (Iranian e-commerce convention: «سوپرمارکت ← حیوانات خانگی»).
 *  - sports_toys hosts toys, baby gear, musical instruments, camping/travel, hunting & fishing.
 *  - office_books hosts stationery, art supplies, office machines, telephony and shop fixtures.
 *  - industrial hosts building services (تأسیسات: plumbing, heating, pools), pneumatics/hydraulics,
 *    automation, pumps, motors, commercial kitchen machines, construction materials, agriculture.
 *  - tools hosts hand/power tools, welding, hardware (یراق), test & measurement instruments, PPE.
 */
